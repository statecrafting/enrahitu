#!/usr/bin/env node
/**
 * The app-manifest composer (spec 035 §3.3).
 *
 * `app-manifest.json` is the ceiling the kernel enforces, and it has to hold
 * two authorships at once: the chassis declares what the shipped application
 * needs, and the organization running it declares what its own extensions
 * need. One hand-edited file cannot carry both, because the chassis file is
 * replaced wholesale on upgrade (spec 035 §3.2), which would silently discard
 * every grant the organization had added to it.
 *
 * So there are two authored files and one derived one:
 *
 *   app-manifest.chassis.json   chassis-owned, replaced on upgrade
 *   app/manifest.json           organization-owned, never touched by an upgrade
 *   app-manifest.json           derived, committed, what the extractor reads
 *
 *   node scripts/gen-manifest.mjs           # write the composed manifest
 *   node scripts/gen-manifest.mjs --check   # fail if the committed file drifted
 *
 * `--check` is the gate, exactly as it is for `gen-infra-config.mjs`: a
 * hand-edit to the derived file is caught at the PR rather than discovered as a
 * capability that exists in the model and in nobody's authored intent.
 *
 * ## The composition rules, and why they refuse rather than merge
 *
 * An overlay may ADD capabilities, services and resources. It may not redefine
 * a chassis one, and the collision is an error rather than a last-writer-wins
 * merge. Precedence is the wrong tool here: a silently overridden capability is
 * a widened ceiling that reads, in the composed file, exactly like a chassis
 * decision. An organization that needs different chassis grants is asking for a
 * chassis change, and that conversation should happen out loud.
 *
 * The one exception is `services[].capabilities`, where an overlay may add
 * grants to a chassis service. That is additive, visible in the composed file,
 * and it is the only way to let an organization's kind be reconciled by a
 * chassis controller.
 */
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const CHASSIS = join(repoRoot, "app-manifest.chassis.json");
const OVERLAY = join(repoRoot, "app", "manifest.json");
const COMPOSED = join(repoRoot, "app-manifest.json");

const BANNER =
  "GENERATED by scripts/gen-manifest.mjs from app-manifest.chassis.json + app/manifest.json. Do not edit; edit one of those and re-run (spec 035).";

/** Fail with a message the reader can act on, never a stack trace. */
function fail(message) {
  console.error(`[gen-manifest] ${message}`);
  process.exit(1);
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (err) {
    fail(`cannot read ${path}: ${String(err)}`);
  }
}

/**
 * Merge the overlay onto the chassis manifest.
 *
 * Deterministic: every composed collection is sorted by its identity key, so
 * the output is a pure function of the two inputs and never of object
 * insertion order (spec 020 §3.5's determinism requirement applies here too,
 * one step before the model).
 */
export function compose(chassis, overlay) {
  const out = structuredClone(chassis);
  out["//"] = BANNER;

  // --- capabilities: additive, collisions refused -------------------------
  const byId = new Map(out.capabilities.map((c) => [c.id, c]));
  for (const cap of overlay.capabilities ?? []) {
    if (byId.has(cap.id)) {
      fail(
        `overlay redefines chassis capability '${cap.id}'. An overlay may add capabilities, ` +
          `never redefine one: a silently overridden grant is a widened ceiling that reads ` +
          `like a chassis decision. Rename it, or propose the change to the chassis.`,
      );
    }
    byId.set(cap.id, cap);
  }
  out.capabilities = [...byId.values()].sort((a, b) => a.id.localeCompare(b.id));

  // --- services: new ones added, chassis ones may gain grants -------------
  for (const [name, decl] of Object.entries(overlay.services ?? {})) {
    const existing = out.services[name];
    if (!existing) {
      out.services[name] = decl;
      continue;
    }
    // The one place precedence is allowed, because it is additive and visible.
    const extra = decl.capabilities ?? [];
    const merged = [...new Set([...(existing.capabilities ?? []), ...extra])].sort();
    for (const key of Object.keys(decl)) {
      if (key !== "capabilities") {
        fail(
          `overlay redefines '${key}' on chassis service '${name}'. An overlay may only add ` +
            `capabilities to a chassis service; everything else about it is the chassis's.`,
        );
      }
    }
    out.services[name] = { ...existing, capabilities: merged };
  }
  out.services = Object.fromEntries(
    Object.entries(out.services).sort(([a], [b]) => a.localeCompare(b)),
  );

  // --- resources: additive per category, collisions refused ---------------
  for (const [category, entries] of Object.entries(overlay.resources ?? {})) {
    const existing = out.resources[category] ?? [];
    const names = new Set(existing.map((e) => e.name));
    for (const entry of entries) {
      if (names.has(entry.name)) {
        fail(
          `overlay redefines chassis resource '${category}/${entry.name}'. Resources are ` +
            `additive; a redefinition would change what a chassis capability is granted on.`,
        );
      }
      names.add(entry.name);
    }
    out.resources[category] = [...existing, ...entries].sort((a, b) =>
      a.name.localeCompare(b.name),
    );
  }

  // Every other top-level member is the chassis's alone. Listing them by
  // refusal rather than by silence means a new one added to the chassis is a
  // legible error for an overlay that tries to set it, not a quiet no-op.
  const overlayOnly = Object.keys(overlay).filter(
    (k) => !["capabilities", "services", "resources"].includes(k) && !k.startsWith("//"),
  );
  if (overlayOnly.length > 0) {
    fail(
      `overlay sets chassis-owned member(s): ${overlayOnly.join(", ")}. An overlay may set ` +
        `capabilities, services and resources. Trust levels, the gate roster, ledger settings, ` +
        `observability and auth are the chassis's, because they are what the chassis is.`,
    );
  }

  return out;
}

function serialize(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function main(argv) {
  const check = argv.includes("--check");
  const chassis = readJson(CHASSIS);
  const overlay = existsSync(OVERLAY) ? readJson(OVERLAY) : {};
  const composed = serialize(compose(chassis, overlay));

  if (!check) {
    writeFileSync(COMPOSED, composed);
    const added = (overlay.capabilities ?? []).length;
    const services = Object.keys(overlay.services ?? {}).length;
    console.log(
      `[gen-manifest] wrote app-manifest.json (overlay: ${added} capabilit${added === 1 ? "y" : "ies"}, ${services} service(s))`,
    );
    return;
  }

  if (!existsSync(COMPOSED)) fail("app-manifest.json is missing; run without --check");
  if (readFileSync(COMPOSED, "utf8") !== composed) {
    fail(
      "app-manifest.json has drifted from its sources. Run `npm run gen:manifest` and commit " +
        "the result. If you hand-edited it, move the edit into app-manifest.chassis.json or " +
        "app/manifest.json, whichever owns it.",
    );
  }
  console.log("[gen-manifest] composed manifest is fresh");
}

// realpath both sides: under a symlinked checkout the raw argv path and the
// module URL disagree and the guard silently no-ops.
if (import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  main(process.argv.slice(2));
}
